# can you change the value inside a list which is contained in set S?
S = {8, 7, 12, "Harry", [1,2]}


# Ans. 
# List inside set → Not allowed
# Modify elements inside set → Not possible (elements must stay immutable)

'''
    Inside Set you can't change value of element, because 
     1) Sets are unindexed => element's order doesn't matter
     2) Sets are unindexed => can not access elements by index
'''